print("✅ index.md generated successfully.")
with open(OUTPUT, "w", encoding="utf-8") as f:

    f.write("# 📚 Repository Index\n\n")
    f.write("> 🤖 This file is automatically generated.\n\n")

    f.write(f"**🕒 Last Updated:** {last_updated}\n\n")

    f.write("## 📊 Repository Statistics\n\n")
    f.write(f"- 📁 Folders: **{len(folders)}**\n")
    f.write(f"- 📄 Markdown Files: **{len(markdown_files)}**\n")
    f.write(f"- 📂 Root Files: **{len(root_files)}**\n\n")

    f.write("---\n\n")

    f.write("## 📂 Documentation\n\n")

    if markdown_files:
        current_folder = ""

        for file in markdown_files:
            path = Path(file)

            folder = path.parent.as_posix()

            if folder == ".":
                folder = "Root"

            if folder != current_folder:
                current_folder = folder
                f.write(f"### 📁 {folder}\n\n")

            f.write(f"- [{path.name}]({file})\n")

        f.write("\n")
    else:
        f.write("_No Markdown files found._\n\n")

    f.write("---\n\n")

    f.write("## 📄 Root Files\n\n")

    if root_files:
        for file in root_files:
            f.write(f"- [{file}]({file})\n")
    else:
        f.write("_No root files found._\n")
